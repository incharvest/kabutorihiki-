def load_universe():
    """discover_lowprice.py の結果（data/lowprice_universe.csv）があればそれを使い、固定リストと合わせる。
    戻り値: {symbol: {"name", "sector", "scale"}}"""
    import csv
    from pathlib import Path
    u = {s: {"name": n, "sector": "", "scale": ""} for s, n in LOWPRICE_CANDIDATES.items()}
    p = Path(__file__).resolve().parent.parent / "data" / "lowprice_universe.csv"
    if p.exists():
        for r in csv.DictReader(open(p, encoding="utf-8")):
            u[r["symbol"]] = {"name": r["銘柄名"], "sector": r["33業種区分"], "scale": r["規模区分"]}
    return u

def tick(price, scale):
    """東証の呼値（TOPIX500採用銘柄は細かい）"""
    t500 = any(k in (scale or "") for k in ("Core30", "Large70", "Mid400"))
    if t500:
        return 0.1 if price <= 1000 else 0.5 if price <= 3000 else 1
    return 1 if price <= 3000 else 5
